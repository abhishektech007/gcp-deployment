#!/usr/bin/env bash
# =============================================================================
# SCRIPT: deploy-frontend.sh
# PURPOSE: High-Performance Static Asset Deployment to Google Cloud Storage (GCS) + Cloud CDN
# ARCHITECTURE LAYER: Edge Delivery Network & Single-Page Application (SPA) Serving
# =============================================================================
#
# OVERVIEW:
#   This script automates the production deployment of an Angular Single-Page
#   Application (SPA) to a Google Cloud Storage bucket configured as an origin
#   behind a Google Cloud CDN-enabled Global External Application Load Balancer.
#
# ARCHITECTURAL CACHING STRATEGY (Differential HTTP Cache Control):
#   Modern SPAs use fingerprint hash-tagging in asset filenames (e.g. main.a8f9c.js).
#   To achieve maximum performance and eliminate deployment race conditions,
#   this script applies a two-tiered caching policy:
#
#   1. Fingerprinted / Hashed Assets (*.js, *.css, *.woff2, *.png, etc.):
#      Header: "Cache-Control: public, max-age=31536000, immutable"
#      Rationale: These files can never change without changing their filename.
#      Browsers and CDN edge nodes cache them permanently (1 year), achieving
#      instant sub-millisecond edge cache hits on subsequent visits.
#
#   2. Application Entrypoint (index.html):
#      Header: "Cache-Control: no-cache, no-store, must-revalidate"
#      Rationale: The entrypoint acts as the manifest linking to current hashed
#      chunks. By forbidding client/CDN caching on index.html, new deployments
#      take effect instantly for all end users without waiting for TTL expiration.
#
#   3. Edge Cache Invalidation:
#      Issues an asynchronous cache invalidation against Cloud CDN for the root
#      paths to purge stale entrypoint copies across Google's worldwide POP locations.
#
# PREREQUISITES:
#   - Google Cloud SDK (gcloud CLI) authenticated with storage administration rights
#   - Pre-compiled Angular application in './dist/frontend/browser'
#   - Target GCS bucket provisioned and configured for static website serving
#
# USAGE:
#   chmod +x deploy-frontend.sh
#   ./deploy-frontend.sh [--env production|staging]
# =============================================================================

# Strict execution policy: fail on error, unset variables, or pipe failures
set -euo pipefail

# -----------------------------------------------------------------------------
# Configuration & Environment Resolution
# -----------------------------------------------------------------------------
ENVIRONMENT_FLAG="${1:---env}"
ENVIRONMENT_NAME="${2:-production}"

# Resolve active Google Cloud Project ID
PROJECT_ID=$(gcloud config get-value project 2>/dev/null || echo '')
if [[ -z "${PROJECT_ID}" || "${PROJECT_ID}" == "(unset)" ]]; then
  echo "[-] ERROR: GCP project is not configured in gcloud CLI."
  echo "    Execute 'gcloud config set project <PROJECT_ID>' before running."
  exit 1
fi

# Target Google Cloud Storage bucket name
BUCKET_NAME="${PROJECT_ID}-frontend-${ENVIRONMENT_NAME}"

# Output directory generated by Angular build (Angular 17+ application builder standard)
DIST_DIR="./dist/frontend/browser"

# Default TTL for non-fingerprinted static media (1 hour)
CDN_DEFAULT_TTL="3600"

# Terminal styling definitions
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
CYAN='\033[0;36m'
NC='\033[0m'

# Logging utility functions
log_info()    { echo -e "${CYAN}[INFO]${NC}  $*"; }
log_success() { echo -e "${GREEN}[✔]${NC}    $*"; }
log_warn()    { echo -e "${YELLOW}[WARN]${NC}  $*"; }
log_error()   { echo -e "${RED}[✘]${NC}   $*" >&2; }

# -----------------------------------------------------------------------------
# Pre-Flight Validation
# -----------------------------------------------------------------------------
echo "============================================================================="
echo " Starting Frontend GCS + Cloud CDN Edge Deployment"
echo " Project Target   : ${PROJECT_ID}"
echo " Storage Bucket   : gs://${BUCKET_NAME}"
echo " Environment Target: ${ENVIRONMENT_NAME}"
echo " Artifact Directory: ${DIST_DIR}"
echo "============================================================================="

# Ensure distribution folder exists before proceeding with cloud sync
if [ ! -d "${DIST_DIR}" ]; then
    log_error "Compiled distribution directory '${DIST_DIR}' was not found."
    log_error "Please execute 'npm run build -- --configuration=${ENVIRONMENT_NAME}' before deploying."
    exit 1
fi

# -----------------------------------------------------------------------------
# Stage 1: Upload Fingerprinted / Hashed Assets (Permanent Immutable Cache)
# -----------------------------------------------------------------------------
# Synchronize JavaScript bundles, CSS stylesheets, web fonts, and images.
# --delete-unmatched-destination-objects: Purges old unreferenced hashes from the bucket.
log_info "Synchronizing fingerprinted assets with 1-year immutable cache headers..."

gcloud storage rsync "${DIST_DIR}" "gs://${BUCKET_NAME}" \
    --recursive \
    --delete-unmatched-destination-objects \
    --cache-control="public, max-age=31536000, immutable" \
    --include="*.js" --include="*.css" --include="*.map" \
    --include="*.woff" --include="*.woff2" --include="*.ttf" \
    --include="*.jpg" --include="*.jpeg" --include="*.png" \
    --include="*.gif" --include="*.svg" --include="*.webp" --include="*.avif" \
    --include="*.ico"

log_success "Fingerprinted bundles synchronized with immutable cache headers."

# -----------------------------------------------------------------------------
# Stage 2: Upload Application Entrypoint (Zero-Cache Header)
# -----------------------------------------------------------------------------
# index.html must NEVER be permanently cached. Browsers must always fetch the
# newest version to discover the newly deployed bundle hashes.
log_info "Uploading 'index.html' entrypoint with strict zero-cache headers..."

gcloud storage cp "${DIST_DIR}/index.html" "gs://${BUCKET_NAME}/index.html" \
    --cache-control="no-cache, no-store, must-revalidate"

log_success "Application entrypoint uploaded (cache bypassed for zero-latency rollout)."

# -----------------------------------------------------------------------------
# Stage 3: Synchronize Unhashed Assets & Static Documents
# -----------------------------------------------------------------------------
# Sync remaining assets (e.g. robots.txt, sitemap.xml, manifest.json) with moderate TTL.
log_info "Synchronizing unhashed static documents (robots.txt, manifests, etc.)..."

gcloud storage rsync "${DIST_DIR}" "gs://${BUCKET_NAME}" \
    --recursive \
    --cache-control="public, max-age=${CDN_DEFAULT_TTL}" \
    --exclude="*.js" --exclude="*.css" --exclude="*.map" \
    --exclude="*.woff" --exclude="*.woff2" --exclude="*.ttf" \
    --exclude="*.jpg" --exclude="*.jpeg" --exclude="*.png" \
    --exclude="*.gif" --exclude="*.svg" --exclude="*.webp" --exclude="*.avif" \
    --exclude="*.ico" --exclude="index.html"

log_success "Unhashed static files synchronized."

# -----------------------------------------------------------------------------
# Stage 4: Invalidate Google Cloud CDN Edge Cache
# -----------------------------------------------------------------------------
# Issue an asynchronous cache invalidation request to Cloud CDN for the root
# and index.html URLs. This purges stale copies from regional edge proxies.
log_info "Initiating edge cache invalidation across Google Cloud CDN..."

URL_MAP_NAME="${PROJECT_ID}-frontend-lb"

# Invalidate /index.html path
gcloud compute url-maps invalidate-cdn-cache "${URL_MAP_NAME}" \
    --path="/index.html" \
    --async \
    2>/dev/null || log_warn "Notice: CDN invalidation skipped (URL Map '${URL_MAP_NAME}' not found or CDN unattached)."

# Invalidate root SPA URL path
gcloud compute url-maps invalidate-cdn-cache "${URL_MAP_NAME}" \
    --path="/" \
    --async \
    2>/dev/null || true

log_success "Edge cache purge signal dispatched."

# -----------------------------------------------------------------------------
# Summary & Operational Metrics
# -----------------------------------------------------------------------------
echo ""
echo "============================================================================="
echo -e "${GREEN} [✔] Frontend Deployment Pipeline Successfully Executed!${NC}"
echo " Storage Origin : gs://${BUCKET_NAME}"
echo " Deployed Files : $(find "${DIST_DIR}" -type f | wc -l) files"
echo " Total Payload  : $(du -sh "${DIST_DIR}" | cut -f1)"
echo " Cache Strategy : Dual-Tier (Immutable Chunks + Uncached Entrypoint)"
echo " CDN Note       : Worldwide edge cache invalidation propagates in ~5-10 minutes."
echo "============================================================================="
